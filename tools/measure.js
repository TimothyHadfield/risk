// Full strength measurement written to docs/strength.json (shown in the app's "How strong?").
//   node tools/measure.js [games]
const fs = require('fs'), path = require('path');
const { table } = require('./sim.js');
const g = +process.argv[2] || 300;
const rows = [];
const pct = (w, n) => Math.round(w / n * 100) + '%';
const t3 = table(['hard', 'medium', 'easy'], g, {});
rows.push(['3 players: Hard / Medium / Easy', g, `${pct(t3.wins.hard, g)} / ${pct(t3.wins.medium, g)} / ${pct(t3.wins.easy, g)}`]);
const t3b = table(['hard', 'medium', 'medium'], g, {});
rows.push(['Hard vs two Medium (fair share 33%)', g, 'Hard ' + pct(t3b.wins.hard, g)]);
for (const [a, b] of [['hard', 'medium'], ['hard', 'easy'], ['medium', 'easy']]) {
  const t = table([a, b], g, {});
  rows.push([`2 players: ${a[0].toUpperCase() + a.slice(1)} vs ${b[0].toUpperCase() + b.slice(1)}`, g, `${pct(t.wins[a], g)} – ${pct(t.wins[b], g)}`]);
}
const out = { measured: new Date().toISOString().slice(0, 10), games: g, rows };
fs.writeFileSync(path.join(__dirname, '..', 'js', 'strength.js'), '// GENERATED by tools/measure.js\nwindow.RISK_STRENGTH = ' + JSON.stringify(rows) + ';\n');
console.log(JSON.stringify(out, null, 1));
