// ---- the drawn board (js/geo.js, generated by tools/buildgeo.mjs from Natural Earth coastlines)
const fs = require('fs');
const G = require('../js/geo.js');
function rings(d) { // our paths: M x,y l dx,dy dx,dy ... z (relative)
  const out = [];
  d.split(/(?=M)/).filter(Boolean).forEach(sub => {
    const nums = (sub.match(/-?\d*\.?\d+/g) || []).map(Number);
    const r = []; let x = nums[0], y = nums[1]; r.push([x, y]);
    for (let i = 2; i + 1 < nums.length; i += 2) { x += nums[i]; y += nums[i + 1]; r.push([x, y]); }
    out.push(r);
  });
  return out;
}
function pip(pt, r) { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > pt[1]) !== (yj > pt[1]) && pt[0] < (xj - xi) * (pt[1] - yi) / (yj - yi) + xi) c = !c; } return c; }
const inside = (pt, rs) => rs.filter(r => pip(pt, r)).length % 2 === 1; // even-odd: holes (lakes) count as outside

test('drawn map: real-coastline board, small enough for a phone', () => {
  assert.strictEqual(G.terr.length, 42);
  assert.match(G.credit, /Natural Earth/);
  const kb = fs.statSync(path.join(__dirname, '..', 'js', 'geo.js')).size / 1024;
  assert.ok(kb < 160, 'geo.js is ' + kb.toFixed(0) + ' KB');
  G.terr.forEach((t, i) => {
    const rs = rings(t.d);
    assert.ok(rs.length >= 1 && rs.every(r => r.length >= 3), M.T[i].name);
    assert.ok(inside([t.x, t.y], rs), 'army badge outside its land: ' + M.T[i].name);
    assert.ok(t.hit && rings(t.hit)[0].length > 5, 'tap area: ' + M.T[i].name);
  });
  assert.strictEqual(G.cont.length, 6);
});

test('drawn map: touching territories are real neighbours; other neighbours get a sea line', () => {
  // vertex of A lying on B's outline -> they touch on the drawing
  const segs = []; G.terr.forEach((t, i) => rings(t.d).forEach(r => r.forEach((p, k) => segs.push([p, r[(k + 1) % r.length], i]))));
  const C = 4, grid = new Map();
  segs.forEach((s, n) => { const k = Math.floor((s[0][0] + s[1][0]) / 2 / C) + ',' + Math.floor((s[0][1] + s[1][1]) / 2 / C); if (!grid.has(k)) grid.set(k, []); grid.get(k).push(n); });
  const dist = (p, a, b) => { const dx = b[0] - a[0], dy = b[1] - a[1], L = dx * dx + dy * dy; let t = L ? ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L : 0; t = Math.max(0, Math.min(1, t)); return Math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy); };
  const touch = new Map();
  segs.forEach(([p, , i]) => {
    const gx = Math.floor(p[0] / C), gy = Math.floor(p[1] / C);
    for (let ox = -2; ox <= 2; ox++) for (let oy = -2; oy <= 2; oy++) (grid.get((gx + ox) + ',' + (gy + oy)) || []).forEach(n => {
      const s = segs[n]; if (s[2] === i || dist(p, s[0], s[1]) > 0.12) return;
      const k = Math.min(i, s[2]) + '-' + Math.max(i, s[2]); touch.set(k, (touch.get(k) || 0) + 1);
    });
  });
  touch.forEach((n, k) => { const [a, b] = k.split('-').map(Number); if (n > 4) assert.ok(M.isAdj(a, b), `${M.T[a].name} touches ${M.T[b].name} on the map but they are not neighbours`); });
  const linked = new Set(G.links.map(([a, b]) => a + '-' + b));
  M.EDGES.forEach(([ka, kb]) => {
    const a = Math.min(M.BY_KEY[ka], M.BY_KEY[kb]), b = Math.max(M.BY_KEY[ka], M.BY_KEY[kb]);
    assert.ok(linked.has(a + '-' + b) || (touch.get(a + '-' + b) || 0) > 0, `${ka}-${kb}: neither touching nor linked`);
  });
});

